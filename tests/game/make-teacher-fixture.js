// node tests/game/make-teacher-fixture.js  -- writes tests/game/fixtures/teacher-today.js, the `teacher` fixture of tests/game/ui-stub.html.
// The fixture is what the Teacher module really returns for a SYNTHETIC teacher (fictional code, classes and chapters; no real data): it
// calls the real tchMissions_ / tchSetupQuests_ / tchChapterQuests_ and the framework's gameTodayView_ on a fixed clock. test-teacher-fixture.js
// fails when the file differs from build(), so the stub cannot drift from the module.
const fs = require('fs'), vm = require('vm'), path = require('path');
const dir = path.join(__dirname, '..', '..', 'apps-script') + path.sep;
const OUT = path.join(__dirname, 'fixtures', 'teacher-today.js');

function build() {
  const ctx = { console, Logger: { log() {} } };
  vm.createContext(ctx);
  ['game-teacher.gs', 'acad-episodes.gs', 'game.gs', 'game-actions.gs', 'game-missions.gs', 'game-windows.gs', 'game-quests.gs']
    .forEach((f) => vm.runInContext(fs.readFileSync(dir + f, 'utf8'), ctx));
  const J = (x) => JSON.parse(JSON.stringify(x));
  const at = (iso) => Date.parse(iso);
  const NOW = new Date('2026-11-10T05:00:00Z'), TUE = '2026-11-10'; // Tue, 10:30 IST
  const CODE = 'NCM/99/01/901';
  const cfg = { teacher: { cwhwFormUrl: 'https://docs.google.com/forms/d/e/STUB/viewform' } };
  const ep = (o) => Object.assign({ first: at('2026-11-02T06:00:00Z'), last: at('2026-11-05T06:00:00Z'), cwaAt: null, cwaFrom: null, remediatedAt: null, plannedCwaDate: null }, o);
  const next = (cls, subj, name, startDate) => ({ cls, subj, ch: ctx.ownAcadNormChapter_(name), name, startDate });
  const key = (cls, subj, name) => cls + '|' + subj + '|' + ctx.ownAcadNormChapter_(name);
  const state = {
    code: CODE, campus: 'LMS2',
    classSubjects: [{ cls: 'Class 7', subj: 'Math' }, { cls: 'Class 8', subj: 'Science' }, { cls: 'M-II', subj: 'Hindi' }, { cls: 'Class 6', subj: 'English' }],
    episodes: [
      ep({ cls: 'Class 7', subj: 'Math', ch: ctx.ownAcadNormChapter_('Fractions'), name: 'Fractions', cwaAt: at('2026-11-05T06:00:00Z'), cwaFrom: 'tag' }), // CWA taken, remediation open
      ep({ cls: 'Class 8', subj: 'Science', ch: ctx.ownAcadNormChapter_('Cells: The Basic Unit'), name: 'Cells: The Basic Unit', last: at('2026-11-09T06:00:00Z') }),  // planned, check pending
      ep({ cls: 'M-II', subj: 'Hindi', ch: ctx.ownAcadNormChapter_('Swar'), name: 'Swar', last: at('2026-11-06T06:00:00Z') }),                                    // Montessori: 3 steps
    ],
    loggedDays: { [TUE]: [{ cls: 'Class 7', subj: 'Math', at: at('2026-11-10T03:00:00Z'), hw: false }, { cls: 'Class 8', subj: 'Science', at: at('2026-11-10T03:40:00Z'), hw: false }] },
    periodsByDay: { Tue: [{ cls: 'Class 7', subj: 'Math' }, { cls: 'Class 8', subj: 'Science' }, { cls: 'Class 6', subj: 'English' }, { cls: 'M-II', subj: 'Hindi' }] },
    nextChapters: [next('Class 7', 'Math', 'Decimals', '2026-11-14'), next('Class 7', 'Math', 'Ratio & Proportion', '2026-11-28'), next('Class 6', 'English', 'The Wonderful Words', '2026-11-16')],
  };
  const plan = (iso) => ({ activity: 'A planned activity', plannedAt: iso });
  const plans = { [key('Class 7', 'Math', 'Fractions')]: plan('2026-11-01T06:00:00Z'), [key('Class 8', 'Science', 'Cells: The Basic Unit')]: plan('2026-11-03T06:00:00Z') };
  const matches = { [key('Class 7', 'Math', 'Fractions')]: { matched: true, confidence: 0.9 } }; // Cells has no row yet: "checking overnight"
  const days = { onTrack: 3, counted: 5, lastMonthOnTrack: 0, lastMonthCounted: 0, showDenominator: false };

  const missions = J(ctx.tchMissions_(state, TUE, true, plans, cfg, NOW, 'teacher@example.org'));
  const view = ctx.gameTodayView_(missions.map((m) => m.id), missions, [], ctx.gameParseConfig_([['Key', 'Value']]), 'Teacher');
  const quests = J(ctx.tchSetupQuests_(state, plans, days, cfg, NOW, {}).concat(ctx.tchChapterQuests_(state, plans, matches, cfg, NOW)));
  return J({ missions: view.missions, next: view.next, quests, daysOnTrack: days });
}

if (require.main === module) {
  fs.writeFileSync(OUT, '// GENERATED by tests/game/make-teacher-fixture.js (synthetic teacher, fixed clock). Do not edit; re-run the script.\nwindow.TEACHER_FIXTURE = ' + JSON.stringify(build(), null, 1) + ';\n');
  console.log('wrote ' + path.relative(process.cwd(), OUT));
}
module.exports = { build, OUT };
